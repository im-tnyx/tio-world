/// Canonical physical geometry values used by the Tio design system.
///
/// Add a value only when it is evidenced by current production UI or approved
/// by an explicit design decision. Semantic/component tokens must alias these
/// physical values instead of redefining them independently.
abstract final class TioSize {
  static const dp4 = 4.0;
  static const dp8 = 8.0;
  static const dp12 = 12.0;
  static const dp16 = 16.0;
  static const dp24 = 24.0;
  static const dp999 = 999.0;
}
